create or replace function public.get_public_profile(p_slug text)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
    select jsonb_build_object(
        'slug', p.public_slug,
        'firstName', p.first_name,
        'lastName', p.last_name,
        'displayName', p.display_name,
        'company', p.company,
        'jobTitle', p.job_title,
        'bio', p.bio,
        'displayImagePath', p.display_image_path,
        'logoPath', p.logo_path,
        'contacts', coalesce((
            select jsonb_agg(jsonb_build_object(
                'kind', c.kind,
                'label', c.label,
                'value', c.value,
                'sortOrder', c.sort_order
            ) order by c.sort_order, c.id)
            from public.profile_contacts c
            where c.user_id = p.user_id and c.is_public
        ), '[]'::jsonb),
        'addresses', coalesce((
            select jsonb_agg(jsonb_build_object(
                'label', a.label,
                'value', a.formatted_address,
                'sortOrder', a.sort_order
            ) order by a.sort_order, a.id)
            from public.profile_addresses a
            where a.user_id = p.user_id and a.is_public
        ), '[]'::jsonb),
        'links', coalesce((
            select jsonb_agg(jsonb_build_object(
                'kind', l.kind,
                'label', l.label,
                'url', l.url,
                'sortOrder', l.sort_order
            ) order by l.sort_order, l.id)
            from public.profile_links l
            where l.user_id = p.user_id and l.is_public
        ), '[]'::jsonb)
    )
    from public.profiles p
    join public.profile_settings s on s.user_id = p.user_id
    where s.is_public
      and p.public_slug is not null
      and lower(p.public_slug) = lower(p_slug)
    limit 1;
$$;

revoke all on function public.get_public_profile(text) from public;
grant execute on function public.get_public_profile(text) to anon, authenticated;

